#!/usr/bin/env node
// Writes each host folder's copy of a shared skill. Every host folder must stand alone (each is
// installed or fetched on its own, without symlinks), so the copies are committed; this script
// keeps them in sync with one source. CI runs it and fails if the committed copies differ.
//
// For each shared/skills/<skill>/:
//   SKILL.md       the common text. Parts that differ per host sit between paired markers,
//                  <!-- name --> default text <!-- /name -->, inline or on their own lines.
//   variants/      <name>.<variant>.md replaces the text between that pair for the hosts that
//                  pick it (one trailing newline is dropped).
//   hosts.json     { cliVersionFrom, hosts: { <host>: { out, variants?, frontmatter?, header? } } }
//                  out: the file to write; variants: { <name>: <variant> }; frontmatter: false
//                  drops the YAML frontmatter (for a plain context file such as GEMINI.md);
//                  header: false leaves out the "generated" comment (claude/, whose file must stay
//                  byte for byte the version under the Claude directory's review).
// {{CLI_VERSION}} becomes the exact box CLI pin read from cliVersionFrom (the file box-cli's
// bump workflow and e2e/cli.mjs read), so all hosts pin the version claude-code/ pins.
//
// Usage: node scripts/gen-skills.mjs        (no dependencies; Node 18+)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const FRONTMATTER = /^---\n[\s\S]*?\n---\n/
const BLOCK = /<!-- ([a-z][\w-]*) -->\n?([\s\S]*?)\n?<!-- \/\1 -->/g

const read = (rel) => fs.readFileSync(path.join(REPO, rel), 'utf8')

function cliVersion(rel) {
  const m = read(rel).match(/@simular-ai\/box@(\d+\.\d+\.\d+)/)
  if (!m) throw new Error(`no exact @simular-ai/box@X.Y.Z pin in ${rel}`)
  return m[1]
}

function render(skillDir, source, host, config, vars) {
  const variants = config.variants || {}
  const used = new Set()
  let text = source.replace(BLOCK, (_, name, fallback) => {
    if (!variants[name]) return fallback
    used.add(name)
    const file = path.join(skillDir, 'variants', `${name}.${variants[name]}.md`)
    return read(file).replace(/\n$/, '')
  })
  for (const name of Object.keys(variants)) {
    if (!used.has(name)) throw new Error(`${host}: no <!-- ${name} --> block in ${skillDir}/SKILL.md`)
  }
  text = text.replace(/\{\{(\w+)\}\}/g, (m, key) => {
    if (!(key in vars)) throw new Error(`${host}: unknown placeholder ${m}`)
    return vars[key]
  })

  const header = config.header === false ? '' : `<!-- Generated by scripts/gen-skills.mjs from ${skillDir}/. Edit it there and re-run the script; don't edit this copy. -->\n`
  const fm = text.match(FRONTMATTER)
  if (!fm) throw new Error(`${skillDir}/SKILL.md must start with YAML frontmatter`)
  const body = text.slice(fm[0].length)
  if (config.frontmatter === false) return header + body
  return header ? `${fm[0]}\n${header}${body}` : text
}

for (const name of fs.readdirSync(path.join(REPO, 'shared', 'skills')).sort()) {
  const skillDir = `shared/skills/${name}`
  const { cliVersionFrom, hosts } = JSON.parse(read(`${skillDir}/hosts.json`))
  const vars = { CLI_VERSION: cliVersion(cliVersionFrom) }
  const source = read(`${skillDir}/SKILL.md`)
  for (const [host, config] of Object.entries(hosts)) {
    const out = render(skillDir, source, host, config, vars)
    const target = path.join(REPO, config.out)
    const before = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null
    if (before !== out) fs.writeFileSync(target, out)
    console.log(`${before === out ? 'unchanged' : 'wrote    '} ${config.out}`)
  }
}
